const assert=require("assert");
const V=require("../validator.js");
assert.equal(V.detectType(["codmueblenue","codstock","descriruta"],"archivo.xls"),"herrajes");
assert.equal(V.detectType(["codmueble","tipopieza","medida1"],"despiece lacas.xls"),"lacas");
assert.equal(V.op("0034639"),"34639");
assert.equal(V.stockKey("0520000046-D"),"520000046");
assert(V.equivalentCode("B120P6.7F","B120P6.7F-SFR"));
const base=V.parseBase("6;B120P6.7F;PT;2;722;597\n6;B120P6.7F;0520000046;2");
const piezas=V.validate([{op:"0034639",codmueble:"B120P6.7F-SFR",tipopieza:"PT",cantreal:2,medida1:722,medida2:597}],base,"melamina","34639");
assert.equal(piezas.status,"APROBADO");
assert(piezas.comparisons[0].xls.includes("Mueble B120P6.7F-SFR"));
assert(piezas.comparisons[0].txt.includes("B120P6.7F"));
const hardware=V.validate([{numordent:"0034639",codmueblenue:"B120P6.7F-SFR",codstock:"0520000046",cantreal:2}],base,"herrajes","34639");
assert.equal(hardware.status,"APROBADO");
const meters=V.validate([{numordent:"0034639",codmueblenue:"B120P6.7F-SFR",codstock:"2505004264",cantreal:2.31}],V.parseBase('6|"B120P6.7F"|"TUBO"|2|1154|1|1|"TUBO"|"2505004264-D"'),"herrajes","34639");
assert.equal(meters.status,"APROBADO");
const auxiliary=V.validate([{numordent:"0034639",codmueblenue:"B120P6.7F-SFR",codstock:"999",cantreal:1}],base,"herrajes","34639");
assert.equal(auxiliary.status,"APROBADO");
assert.equal(auxiliary.notComparable,1);
const wrongOp=V.validate([{op:"111",codmueble:"B120P6.7F",tipopieza:"PT",cantreal:2,medida1:722,medida2:597}],base,"melamina","34639");
assert.equal(wrongOp.status,"RECHAZADO");
assert(wrongOp.issues[0].txt.includes("34639"));
